const lookup = (key) => key.split('.').reduce((node, part) => (node == null ? node : node[part]), X);

/** tx('turn-counters.recalled', { cast: 1, capacity: 2 }) */
export function tx(key, vars = {}) {
  let value = lookup(key);
  if (value == null) return key;
  if (Array.isArray(value)) value = vars.n === 1 ? value[0] : value[1];
  return String(value).replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}
